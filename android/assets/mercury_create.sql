create table t_message_group (_id integer primary key autoincrement,
                            `group_id` text,
                            `action_url` text,
                            `icon_url` text,
                            `title` text,
                            `description` text,
                            `event_name` text,
                            `priority` integer,
                            `count` integer,
                            `attribute` integer,
                            `last_update_time` integer,
                            `expired_date` integer);
create table t_message_item (_id integer primary key autoincrement,
                            `group_id` text,
                            `item_id` text,
                            `show_type` integer,
                            `post_time` integer,
                            `counter_url_rename` text,
                            `content` text);