using System.Security.Permissions;

namespace System.Web.UI.WebControls;

[AspNetHostingPermission(SecurityAction.LinkDemand, Level = AspNetHostingPermissionLevel.Minimal)]
[AspNetHostingPermission(SecurityAction.InheritanceDemand, Level = AspNetHostingPermissionLevel.Minimal)]
public sealed class AutoGeneratedFieldProperties : IStateManager
{
	private StateBag ViewState = new StateBag();

	public string DataField
	{
		get
		{
			return ViewState.GetString("DataField", string.Empty);
		}
		set
		{
			ViewState["DataField"] = value;
		}
	}

	public bool IsReadOnly
	{
		get
		{
			return ViewState.GetBool("IsReadOnly", def: false);
		}
		set
		{
			ViewState["IsReadOnly"] = value;
		}
	}

	public string Name
	{
		get
		{
			return ViewState.GetString("Name", string.Empty);
		}
		set
		{
			ViewState["Name"] = value;
		}
	}

	public Type Type
	{
		get
		{
			object obj = ViewState["Type"];
			if (obj != null)
			{
				return (Type)obj;
			}
			return null;
		}
		set
		{
			ViewState["Type"] = value;
		}
	}

	bool IStateManager.IsTrackingViewState => ViewState.IsTrackingViewState;

	void IStateManager.LoadViewState(object state)
	{
		ViewState.LoadViewState(state);
	}

	object IStateManager.SaveViewState()
	{
		return ViewState.SaveViewState();
	}

	void IStateManager.TrackViewState()
	{
		ViewState.TrackViewState();
	}
}
