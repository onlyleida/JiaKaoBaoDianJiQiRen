	private void LoadDataKeyArrayState(object[] state, out DataKeyArray keys)
	{
		List<DataKey> dataKeyList = DataKeyList;
		string[] array = DataKeyNames;
		int capacity = array.Length;
		for (int i = 0; i < state.Length; i++)
