		object obj = base.SaveControlState();
		return new object[12]
		{
			obj,
			pageIndex,
			selectedIndex,
			editIndex,
			sortExpression,
			sortDirection,
			DataKeyNames,
			SaveDataKeyArrayState(keys),
			(oldEditValues == null) ? null : ((IStateManager)oldEditValues).SaveViewState(),
