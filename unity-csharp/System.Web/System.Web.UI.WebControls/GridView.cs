	protected override bool OnBubbleEvent(object source, EventArgs e)
	{
		if (e is GridViewCommandEventArgs e2)
		{
			bool causesValidation = false;
			if (e2.CommandSource is IButtonControl { CausesValidation: not false } buttonControl)
			{
				Page.Validate(buttonControl.ValidationGroup);
				causesValidation = true;
			}
			OnRowCommand(e2);
			string text = e2.CommandArgument as string;
			if (text == null || text.Length == 0)
			{
				GridViewRow row = e2.Row;
				if (row != null)
				{
					text = row.RowIndex.ToString();
				}
			}
			ProcessEvent(e2.CommandName, text, causesValidation);
			return true;
		}
		return base.OnBubbleEvent(source, e);
	}

