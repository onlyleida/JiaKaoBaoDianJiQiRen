	protected virtual void RaisePostBackEvent(string eventArgument)
	{
		int num = eventArgument.IndexOf('$');
		GridViewCommandEventArgs e = ((num == -1) ? new GridViewCommandEventArgs(this, new CommandEventArgs(eventArgument, null)) : new GridViewCommandEventArgs(this, new CommandEventArgs(eventArgument.Substring(0, num), eventArgument.Substring(num + 1))));
		OnRowCommand(e);
		ProcessEvent(e.CommandName, (string)e.CommandArgument, causesValidation: false);
	}

	private void ProcessEvent(string eventName, string param, bool causesValidation)
	{
		switch (eventName)
		{
		case "Page":
		{
			int num2 = -1;
			switch (param)
			{
			case "First":
				num2 = 0;
				break;
			case "Last":
				num2 = PageCount - 1;
				break;
			case "Next":
				num2 = PageIndex + 1;
				break;
			case "Prev":
				num2 = PageIndex - 1;
				break;
			default:
			{
				int result = 0;
				int.TryParse(param, out result);
				num2 = result - 1;
				break;
			}
			}
			SetPageIndex(num2);
			break;
		}
		case "First":
			SetPageIndex(0);
			break;
		case "Last":
			SetPageIndex(PageCount - 1);
			break;
		case "Next":
			if (PageIndex < PageCount - 1)
			{
				SetPageIndex(PageIndex + 1);
			}
			break;
		case "Prev":
			if (PageIndex > 0)
			{
				SetPageIndex(PageIndex - 1);
			}
			break;
		case "Select":
			SelectRow(int.Parse(param));
			break;
		case "Edit":
			SetEditRow(int.Parse(param));
			break;
		case "Update":
		{
			int num = int.Parse(param);
			UpdateRow(Rows[num], num, causesValidation);
			break;
		}
		case "Cancel":
			CancelEdit();
			break;
		case "Delete":
			DeleteRow(int.Parse(param));
			break;
		case "Sort":
			Sort(param);
			break;
		}
	}

	private void Sort(string newSortExpression)
	{
		SortDirection sortDirection = SortDirection.Ascending;
		if (sortExpression == newSortExpression && this.sortDirection == SortDirection.Ascending)
		{
			sortDirection = SortDirection.Descending;
		}
		Sort(newSortExpression, sortDirection);
	}

