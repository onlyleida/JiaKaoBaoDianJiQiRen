	private void InsertItem(string param, bool causesValidation)
	{
		if (!causesValidation || Page == null || Page.IsValid)
		{
			if (CurrentMode != DetailsViewMode.Insert)
			{
				throw new HttpException();
			}
			currentEditNewValues = GetRowValues(includeReadOnlyFields: false, includePrimaryKey: true);
			DetailsViewInsertEventArgs e = new DetailsViewInsertEventArgs(param, currentEditNewValues);
			OnItemInserting(e);
			if (!e.Cancel && IsBoundUsingDataSourceID)
			{
				(GetData() ?? throw new HttpException("The DataSourceView associated to data bound control was null")).Insert(currentEditNewValues, InsertCallback);
			}
		}
	}

	private bool InsertCallback(int recordsAffected, Exception exception)
	{
		DetailsViewInsertedEventArgs e = new DetailsViewInsertedEventArgs(recordsAffected, exception, currentEditNewValues);
		OnItemInserted(e);
		if (!e.KeepInInsertMode)
		{
			EndRowEdit();
		}
		return e.ExceptionHandled;
	}

	public virtual void DeleteItem()
	{
		currentEditRowKeys = DataKey.Values;
		currentEditNewValues = GetRowValues(includeReadOnlyFields: true, includePrimaryKey: false);
		DetailsViewDeleteEventArgs e = new DetailsViewDeleteEventArgs(PageIndex, currentEditRowKeys, currentEditNewValues);
		OnItemDeleting(e);
		if (!e.Cancel && IsBoundUsingDataSourceID)
		{
			DataSourceView data = GetData();
			if (data != null)
			{
				data.Delete(currentEditRowKeys, currentEditNewValues, DeleteCallback);
			}
			else
			{
				DetailsViewDeletedEventArgs e2 = new DetailsViewDeletedEventArgs(0, null, currentEditRowKeys, currentEditNewValues);
				OnItemDeleted(e2);
			}
			if (PageIndex > 0 && PageIndex == PageCount - 1)
			{
				PageIndex--;
			}
			RequireBinding();
		}
	}

	private bool DeleteCallback(int recordsAffected, Exception exception)
	{
		DetailsViewDeletedEventArgs e = new DetailsViewDeletedEventArgs(recordsAffected, exception, currentEditRowKeys, currentEditNewValues);
		OnItemDeleted(e);
		return e.ExceptionHandled;
	}

