			footerRow = CreateRow(-1, DataControlRowType.Footer, DataControlRowState.Normal);
			DataControlFieldCell dataControlFieldCell2 = new DataControlFieldCell(null);
			dataControlFieldCell2.ColumnSpan = 2;
