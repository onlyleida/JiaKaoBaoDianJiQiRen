	protected virtual void RaisePostBackEvent(string eventArgument)
	{
		ValidateEvent(UniqueID, eventArgument);
		int num = eventArgument.IndexOf('$');
		CommandEventArgs originalArgs = ((num == -1) ? new CommandEventArgs(eventArgument, null) : new CommandEventArgs(eventArgument.Substring(0, num), eventArgument.Substring(num + 1)));
		ProcessCommand(new DetailsViewCommandEventArgs(this, originalArgs), causesValidation: false);
	}

	private void ProcessEvent(string eventName, string param, bool causesValidation)
	{
		switch (eventName)
		{
		case "Page":
		{
			int num = -1;
			switch (param)
			{
			case "First":
				num = 0;
				break;
			case "Last":
				num = PageCount - 1;
				break;
			case "Next":
				num = PageIndex + 1;
				break;
			case "Prev":
				num = PageIndex - 1;
				break;
			default:
			{
				int result = 0;
				int.TryParse(param, out result);
				num = result - 1;
				break;
			}
			}
			SetPageIndex(num);
			break;
		}
		case "First":
			SetPageIndex(0);
			break;
		case "Last":
			SetPageIndex(PageCount - 1);
			break;
		case "Next":
			if (PageIndex < PageCount - 1)
			{
				SetPageIndex(PageIndex + 1);
			}
			break;
		case "Prev":
			if (PageIndex > 0)
			{
				SetPageIndex(PageIndex - 1);
			}
			break;
		case "Edit":
			ProcessChangeMode(DetailsViewMode.Edit);
			break;
		case "New":
			ProcessChangeMode(DetailsViewMode.Insert);
			break;
		case "Update":
			UpdateItem(param, causesValidation);
			break;
		case "Cancel":
			CancelEdit();
			break;
		case "Delete":
			DeleteItem();
			break;
		case "Insert":
			InsertItem(causesValidation);
			break;
		}
	}

	public void SetPageIndex(int index)
	{
		DetailsViewPageEventArgs e = new DetailsViewPageEventArgs(index);
		OnPageIndexChanging(e);
		if (!e.Cancel && IsBoundUsingDataSourceID && e.NewPageIndex >= 0 && e.NewPageIndex < PageCount)
		{
			EndRowEdit(switchToDefaultMode: false);
			PageIndex = e.NewPageIndex;
			OnPageIndexChanged(EventArgs.Empty);
		}
	}

